using System.Globalization;
using System.Text;
using InkvoltPdf.Core;

namespace InkvoltPdf.FormsCorpus;

/// <summary>
/// The UI half: a <c>--script</c> for Inkvolt PDF that fills a form as a person does (the page fitted, a real mouse
/// click on each field, real key messages typed, Tab to move on), then saves with Ctrl+S over the file it opened; and the
/// check of what it saved.
/// </summary>
public static class UiScript
{
    public sealed record Expected(string Name, string Kind, string Value, string? State);

    /// <param name="slowFill">Each batch of values takes this many milliseconds longer (a PC under load), so the next click and keys arrive while it is written.</param>
    public static (string Steps, List<Expected> Expected) Build(byte[] data, int count, int slowFill = 0)
    {
        var widgets = FormEditor.Read(data, null);
        var scripts = FormsHarness.Scripts(data);
        var fields = FormEditor.DataFields(data, null).ToDictionary(f => f.Name);
        var steps = new StringBuilder();
        var expected = new List<Expected>();
        steps.AppendLine("# generated by pdf/tools/forms-corpus (script): fills fields with the mouse and keys, then saves");
        steps.AppendLine("wait 2500");
        steps.AppendLine("zoom fitpage");
        if (slowFill > 0) steps.AppendLine($"slowfill {slowFill}");
        var page = -1;
        var n = 0;
        foreach (var group in widgets.GroupBy(w => w.FieldName))
        {
            if (expected.Count >= count) break;
            if (!fields.TryGetValue(group.Key, out var f) || f.ReadOnly) continue;
            var ws = group.Where(w => !w.ReadOnly && !w.Calculated && w.Rect.Width >= 6 && w.Rect.Height >= 6).ToList();
            if (ws.Count == 0 || group.Any(w => w.Calculated)) continue;
            var target = f.Kind == FormFieldKind.Radio ? ws.LastOrDefault(w => w.OnState is not null) : ws[0];
            if (target is null || f.Kind == FormFieldKind.CheckBox && target.OnState is null) continue;
            if (f.Kind == FormFieldKind.Choice && (f.MultiSelect || f.Options.Count < 2)) continue;
            if (f.Kind == FormFieldKind.Text && ws[0].Password) continue;
            n++;
            if (target.PageIndex != page)
            {
                page = target.PageIndex;
                steps.AppendLine($"page {page + 1}");
                steps.AppendLine("wait 600");
            }
            var x = (target.Rect.X + target.Rect.Width / 2).ToString("0.#", CultureInfo.InvariantCulture);
            var y = (target.Rect.Y + target.Rect.Height / 2).ToString("0.#", CultureInfo.InvariantCulture);
            steps.AppendLine($"mouse click {page + 1} {x} {y}");
            steps.AppendLine("wait 300");
            switch (f.Kind)
            {
                case FormFieldKind.Text:
                {
                    // What the field's format accepts (digits, a date in its format...), typed on one line.
                    scripts.TryGetValue(f.Name, out var js);
                    var comb = js is not null && (js.Flags & (1 << 24)) != 0;
                    var value = FormsHarness.TextValue(n, FormsHarness.FormatOf(js), js, f.MaxLength, multiline: false, comb);
                    steps.AppendLine($"keys {value.Replace(" ", "{sp}")}");
                    steps.AppendLine("key Tab");
                    expected.Add(new Expected(f.Name, "Text", value, null));
                    break;
                }
                case FormFieldKind.Choice:
                {
                    var label = f.Labels.Count > 1 ? f.Labels[1] : f.Options[1];
                    steps.AppendLine($"type {label}");
                    steps.AppendLine("key Tab");
                    expected.Add(new Expected(f.Name, "Choice", f.Options[1], null));
                    break;
                }
                default:
                    // A click toggles a check box: one that was ticked ends up unticked.
                    var off = f.Kind == FormFieldKind.CheckBox && f.Value is not ("Off" or "");
                    expected.Add(new Expected(f.Name, f.Kind.ToString(), off ? "Off" : target.OnState!, target.OnState));
                    break;
            }
            steps.AppendLine("wait 400");
            // A form script's alert (a value it refuses) is modal: log what it says, then dismiss it as a person would.
            steps.AppendLine("windows");
            steps.AppendLine("closedialog");
        }
        steps.AppendLine("fields 3");
        // Ctrl+S, as a person saves: the tab first writes the values still queued, then saves over the opened file.
        steps.AppendLine("key S ctrl");
        steps.AppendLine("waitsaved");
        steps.AppendLine("state");
        steps.AppendLine("exit");
        return (steps.ToString(), expected);
    }

    /// <summary>Problems with what the app saved: a field it didn't keep, or kept another value.</summary>
    public static List<string> Check(byte[]? saved, List<Expected> expected)
    {
        if (saved is null) return ["the app saved nothing"];
        var problems = new List<string>();
        var after = FormEditor.DataFields(saved, null).GroupBy(f => f.Name).ToDictionary(g => g.Key, g => g.First());
        foreach (var e in expected)
        {
            if (!after.TryGetValue(e.Name, out var got))
            {
                problems.Add($"ui-field-gone\t{e.Name}");
                continue;
            }
            var ok = e.Kind switch
            {
                "Text" => got.Value == e.Value || Digits(got.Value).Length > 0 && Digits(got.Value) == Digits(e.Value),
                "Choice" => got.Value == e.Value,
                _ when e.Value == "Off" => got.Value is "Off" or "",
                _ => got.Value is not ("Off" or ""),
            };
            if (!ok) problems.Add($"ui-value-not-kept\t{e.Name}\t{e.Kind}: typed/clicked '{e.Value}', saved '{got.Value}'");
        }
        return problems;
    }

    private static string Digits(string s) => new([.. s.Where(char.IsAsciiDigit)]);
}
